import 'package:cloud_firestore/cloud_firestore.dart';
import '../models/workout_log.dart';

/// Wraps every Firestore call the app needs for the WorkoutLog collection,
/// so no screen or provider ever calls FirebaseFirestore.instance directly.
/// Mirrors the AuthService pattern used for Firebase Authentication.
class WorkoutLogService {
  final CollectionReference<Map<String, dynamic>> _logs = FirebaseFirestore
      .instance
      .collection('WorkoutLog');

  /// READ (select all, filtered by user) - a live stream, newest first.
  /// This is the single query every screen (Home, Workout Session, and
  /// later Recommendations/Analysis) reads from.
  Stream<List<WorkoutLog>> streamLogs(String userId) {
    return _logs
        .where('userId', isEqualTo: userId)
        .orderBy('loggedAt', descending: true)
        .snapshots()
        .map((snapshot) => snapshot.docs.map(WorkoutLog.fromDoc).toList());
  }

  /// CREATE - Firestore auto-generates the document ID (matches the
  /// "Unique ID auto-generated by Firestore" behaviour in your Part 1
  /// data dictionary).
  Future<void> addLog(WorkoutLog log) {
    return _logs.add(log.toMap());
  }

  /// UPDATE - targets the specific document by its Firestore ID.
  Future<void> updateLog(WorkoutLog log) {
    return _logs.doc(log.logId).update(log.toMap());
  }

  /// DELETE
  Future<void> deleteLog(String logId) {
    return _logs.doc(logId).delete();
  }

  // ---------------------------------------------------------------------
  // ADVANCED QUERIES (Part 3 rubric: "Advanced queries" 2.5%)
  //
  // These are real Firestore queries (each hits the server, not the
  // already-streamed list from streamLogs()) and are called on demand
  // from the Analysis tab's "Explore Queries" card - see
  // widgets/advanced_queries_card.dart. Each one demonstrates a distinct
  // query shape called out in the rubric.
  // ---------------------------------------------------------------------

  /// Select with filter criteria (other than identifier).
  /// Every set logged for one muscle group, e.g. every "Chest" set.
  Future<List<WorkoutLog>> logsByMuscleGroup(
    String userId,
    String muscleGroup,
  ) async {
    final snapshot = await _logs
        .where('userId', isEqualTo: userId)
        .where('muscleGroup', isEqualTo: muscleGroup)
        .get();
    return snapshot.docs.map(WorkoutLog.fromDoc).toList();
  }

  /// Select with multiple filter criteria (same field).
  /// Sets whose weight falls within [minKg, maxKg] - two range clauses on
  /// the same 'weight' field.
  Future<List<WorkoutLog>> logsInWeightRange(
    String userId,
    double minKg,
    double maxKg,
  ) async {
    final snapshot = await _logs
        .where('userId', isEqualTo: userId)
        .where('weight', isGreaterThanOrEqualTo: minKg)
        .where('weight', isLessThanOrEqualTo: maxKg)
        .get();
    return snapshot.docs.map(WorkoutLog.fromDoc).toList();
  }

  /// Select with multiple filter criteria (different fields).
  /// Sets for one muscle group logged since a given date - filters on
  /// 'muscleGroup' and 'loggedAt' together.
  Future<List<WorkoutLog>> recentLogsByMuscleGroup(
    String userId,
    String muscleGroup,
    DateTime since,
  ) async {
    final snapshot = await _logs
        .where('userId', isEqualTo: userId)
        .where('muscleGroup', isEqualTo: muscleGroup)
        .where('loggedAt', isGreaterThanOrEqualTo: Timestamp.fromDate(since))
        .get();
    return snapshot.docs.map(WorkoutLog.fromDoc).toList();
  }

  /// Select with sort order.
  /// The user's heaviest logged sets, heaviest first - a simple
  /// "Personal Records" list, sorted server-side by Firestore.
  Future<List<WorkoutLog>> heaviestSets(String userId, {int limit = 5}) async {
    final snapshot = await _logs
        .where('userId', isEqualTo: userId)
        .orderBy('weight', descending: true)
        .limit(limit)
        .get();
    return snapshot.docs.map(WorkoutLog.fromDoc).toList();
  }

  /// Select with aggregation.
  /// Total number of sets ever logged, using Firestore's server-side
  /// count() aggregate query (not client-side docs.length after fetching
  /// everything).
  Future<int> totalSetsLogged(String userId) async {
    final aggregate = await _logs
        .where('userId', isEqualTo: userId)
        .count()
        .get();
    return aggregate.count ?? 0;
  }
}
